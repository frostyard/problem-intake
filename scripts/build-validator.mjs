#!/usr/bin/env node
// Compile schema/v1.json (a byte copy of frostyard/core
// docs/specs/schemas/problem-report/v1.json) to a standalone validator.
// Workers forbid eval and new Function, so Ajv cannot compile at run time.
//
//   node scripts/build-validator.mjs          write src/generated/validate-v1.js
//   node scripts/build-validator.mjs --check  fail when the committed file differs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import ucs2lengthModule from "ajv/dist/runtime/ucs2length.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "schema/v1.json");
const outPath = resolve(root, "src/generated/validate-v1.js");

const args = process.argv.slice(2);
const check = args.includes("--check");
if (args.some((a) => a !== "--check")) {
  process.stderr.write("Usage: node scripts/build-validator.mjs [--check]\n");
  process.exit(2);
}

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  code: { source: true, esm: true, lines: true },
});
const validate = ajv.compile(schema);
const header =
  "// Generated by scripts/build-validator.mjs from schema/v1.json. Do not edit.\n" +
  "// Regenerate with `npm run build:validator`; `npm run check:validator` fails on drift.\n" +
  "/* eslint-disable */\n// @ts-nocheck\n";
// Ajv's standalone output imports its runtime helper with require(), which a
// Worker bundle cannot run. Inline Ajv's own helper (maxLength counts code
// points), and refuse any other require().
const ucs2length = ucs2lengthModule.default ?? ucs2lengthModule;
let body = standaloneCode(ajv, validate);
body = body.replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  (_match, name) => `const ${name} = ucs2length;`,
);
if (body.includes("require(")) {
  process.stderr.write("FAIL: the generated validator still holds a require() call\n");
  process.exit(1);
}
const code = `${header}${body}\n// Inlined from ajv/dist/runtime/ucs2length.js.\n${ucs2length.toString()}\n`;

if (check) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // A missing file is drift too.
  }
  if (current !== code) {
    process.stderr.write(
      "FAIL: src/generated/validate-v1.js is not the build of schema/v1.json; run `npm run build:validator`\n",
    );
    process.exit(1);
  }
  process.stdout.write("ok: src/generated/validate-v1.js matches schema/v1.json\n");
} else {
  writeFileSync(outPath, code);
  process.stdout.write("wrote src/generated/validate-v1.js\n");
}
